func TestPostgresAutoConfigBindsEmptyGeneratedOverride(t *testing.T) {
	j := postgresFrozenFixture()
	j.PostgresUID, j.PostgresGID = uint32(os.Getuid()), uint32(os.Getgid())
	b := newPostgresBackend(testManager(t))
	b.sysroot = t.TempDir()
	if e := os.MkdirAll(b.data(j), 0700); e != nil {
		t.Fatal(e)
	}
	path := filepath.Join(b.data(j), "postgresql.auto.conf")
	original := []byte("# Do not edit this file manually!\n# It will be overwritten by ALTER SYSTEM.\n")
	if e := os.WriteFile(path, original, 0600); e != nil {
		t.Fatal(e)
	}
	h, e := b.observeAutoConfig(j)
	if e != nil || h != digest(original) {
		t.Fatalf("generated override rejected: %v", e)
	}
	j.AutoConfigSHA256 = h
	for _, value := range []string{"hba_file = '/foreign/hba'\n", "include = '/foreign/override'\n", "listen_addresses='*'\n", "# different empty override\n", "# comment\x00\n"} {
		if e := os.WriteFile(path, []byte(value), 0600); e != nil {
			t.Fatal(e)
		}
		if _, e = b.observeAutoConfig(j); e == nil {
			t.Fatal("override drift accepted")
		}
	}
	if e := os.WriteFile(path, original, 0644); e != nil {
		t.Fatal(e)
	}
	if e := os.Chmod(path, 0644); e != nil {
		t.Fatal(e)
	}
	if _, e = b.observeAutoConfig(j); e == nil {
		t.Fatal("public override accepted")
	}
	if e := os.Remove(path); e != nil {
		t.Fatal(e)
	}
	target := filepath.Join(b.sysroot, "foreign")
	if e := os.WriteFile(target, original, 0600); e != nil {
		t.Fatal(e)
	}
	if e := os.Symlink(target, path); e != nil {
		t.Fatal(e)
	}
	if _, e = b.observeAutoConfig(j); e == nil {
		t.Fatal("symlink override accepted")
	}
}

func TestPostgresEffectiveSecuritySettingsCannotRedirectRecordedFiles(t *testing.T) {
	j := postgresFrozenFixture()
	j.ClusterID = "1234567890"
	b := newPostgresBackend(testManager(t))
	good := postgresSecurityObservation{System: j.ClusterID, Data: b.data(j), Listen: "127.0.0.1", Port: strconv.Itoa(j.Draft.Port), Config: filepath.Join(b.configDir(j), "postgresql.conf"), HBA: filepath.Join(b.configDir(j), "pg_hba.conf"), Ident: filepath.Join(b.configDir(j), "pg_ident.conf"), Password: "scram-sha-256", SSL: "off"}
	if !b.validSecurityObservation(j, good) {
		t.Fatal("bound settings rejected")
	}
	cases := map[string]func(*postgresSecurityObservation){
		"system":   func(a *postgresSecurityObservation) { a.System = "other" },
		"data":     func(a *postgresSecurityObservation) { a.Data = "/foreign/data" },
		"listen":   func(a *postgresSecurityObservation) { a.Listen = "*" },
		"port":     func(a *postgresSecurityObservation) { a.Port = "5432" },
		"config":   func(a *postgresSecurityObservation) { a.Config = "/foreign/postgresql.conf" },
		"hba":      func(a *postgresSecurityObservation) { a.HBA = "/foreign/hba.conf" },
		"ident":    func(a *postgresSecurityObservation) { a.Ident = "/foreign/ident.conf" },
		"password": func(a *postgresSecurityObservation) { a.Password = "md5" },
		"ssl":      func(a *postgresSecurityObservation) { a.SSL = "on" },
	}
	for name, change := range cases {
		t.Run(name, func(t *testing.T) {
			a := good
			change(&a)
			if b.validSecurityObservation(j, a) {
				t.Fatal("changed running setting accepted")
			}
		})
	}
}

func TestPostgresPasswordProofRejectsMissingCredential(t *testing.T) {
	for _, dsn := range []string{"postgres://role@127.0.0.1/db", "postgres://role:@127.0.0.1/db", "%"} {
		if !errors.Is(postgresRequirePassword(context.Background(), dsn), ErrInput) {
			t.Fatal("missing/invalid private password accepted")
		}
	}
}

// Real SCRAM and trust endpoints are both required: the latter reproduces the
// false-positive case that successful correct-password login cannot detect.
func TestPostgresPasswordProofAgainstActualSCRAMAndTrust(t *testing.T) {
	scram, trust := os.Getenv("RIXA_POSTGRES_AUTH_SCRAM_DSN"), os.Getenv("RIXA_POSTGRES_AUTH_TRUST_DSN")
	if scram == "" || trust == "" {
		t.Skip("requires two explicit owned actual PostgreSQL authentication fixtures")
	}
	for _, dsn := range []string{scram, trust} {
		c, e := postgresConnect(context.Background(), dsn)
		if e != nil {
			t.Fatal("owned correct-password fixture is unavailable")
		}
		_ = c.Close(context.Background())
	}
	if e := postgresRequirePassword(context.Background(), scram); e != nil {
		t.Fatal("actual SCRAM invalid-password rejection was not established")
	}
	if !errors.Is(postgresRequirePassword(context.Background(), trust), ErrAuthority) {
		t.Fatal("actual trust authentication was accepted as password enforcement")
	}
}

func TestPostgresJournalRequiresBoundAutoConfigAfterCluster(t *testing.T) {
	j := postgresFrozenFixture()
	for _, stage := range postgresStages {
		j.Attempts[stage] = "verified"
		if stage == "cluster" {
			break
		}
	}
	h := strings.Repeat("a", 64)
	j.Stage = "cluster"
	j.ClusterID = "1234567890"
	j.PostgresUID, j.PostgresGID = 100, 100
	j.DataIdentity = "1:2"
	j.ConfigSHA256, j.HBASHA256, j.BinarySHA256 = h, h, h
	j.Updated = "2026-10-30T00:00:00Z"
	if validPostgresJournal(j) {
		t.Fatal("verified cluster without auto-conf binding accepted")
	}
	j.AutoConfigSHA256 = h
	if !validPostgresJournal(j) {
		t.Fatal("complete cluster binding rejected")
	}
}

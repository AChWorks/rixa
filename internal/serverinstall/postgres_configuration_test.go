func TestPostgresConfigurationBoundsFailureDiagnostic(t *testing.T) {
	b, j, _ := postgresConfigurationFixture(t)
	cause := errors.New("fixture native parser exit")
	_, _, _, e := b.observeConfiguration(context.Background(), j, func(_ context.Context, cmd *exec.Cmd) error {
		_, writeError := io.WriteString(cmd.Stderr, "FATAL: syntax at line 19\n"+strings.Repeat("x", 60<<10))
		if writeError != nil {
			t.Fatal(writeError)
		}
		return cause
	})
	if !errors.Is(e, ErrState) || !errors.Is(e, cause) || len(e.Error()) > 12<<10 {
		t.Fatal("configuration failure diagnostic lost its cause or finite bound")
	}
	for _, context := range []string{"setting data_directory", "syntax at line 19", "[diagnostic truncated]"} {
		if !strings.Contains(e.Error(), context) {
			t.Fatalf("bounded diagnostic erased %q", context)
		}
	}
}

func postgresConfigurationFixture(t *testing.T) (*postgresBackend, *postgresJournal, map[string]string) {
	t.Helper()
	b := newPostgresBackend(testManager(t))
	b.sysroot = t.TempDir()
	j := postgresFrozenFixture()
	j.PostgresUID, j.PostgresGID = uint32(os.Geteuid()), uint32(os.Getegid())
	if j.PostgresUID == 0 {
		j.PostgresUID, j.PostgresGID = 65534, 65534
	}
	j.PostgresGroups = []uint32{j.PostgresGID}
	for _, path := range []string{b.data(j), filepath.Join(b.configDir(j), "conf.d")} {
		if e := os.MkdirAll(path, 0700); e != nil {
			t.Fatal(e)
		}
	}
	// The parser result, not a literal assignment in this generated file, must
	// establish ssl=off. This test substitutes query results; it is not a real
	// PostgreSQL provisioning or parser-default proof.
	files := map[string]string{
		filepath.Join(b.configDir(j), "postgresql.conf"): "# generated configuration; ssl is omitted\n",
		filepath.Join(b.configDir(j), "pg_hba.conf"):     "local all all peer\nhost all all 127.0.0.1/32 scram-sha-256\n",
		filepath.Join(b.data(j), "postgresql.auto.conf"): "# Do not edit this file manually!\n",
	}
	for path, text := range files {
		if e := os.WriteFile(path, []byte(text), 0600); e != nil {
			t.Fatal(e)
		}
	}
	if os.Geteuid() == 0 {
		if e := os.Chown(filepath.Join(b.data(j), "postgresql.auto.conf"), int(j.PostgresUID), int(j.PostgresGID)); e != nil {
			t.Fatal(e)
		}
	}
	return b, j, map[string]string{
		"data_directory": b.data(j), "port": strconv.Itoa(j.Draft.Port),
		"listen_addresses": "127.0.0.1", "password_encryption": "scram-sha-256", "ssl": "off",
		"config_file": filepath.Join(b.configDir(j), "postgresql.conf"),
		"hba_file":    filepath.Join(b.configDir(j), "pg_hba.conf"), "ident_file": filepath.Join(b.configDir(j), "pg_ident.conf"),
	}
}

func TestPostgresConfigurationUsesBoundedParserQueriesAndRecordedPrivileges(t *testing.T) {
	b, j, values := postgresConfigurationFixture(t)
	extra := j.PostgresGID + 1
	j.PostgresGroups = append(j.PostgresGroups, extra)
	sort.Slice(j.PostgresGroups, func(i, k int) bool { return j.PostgresGroups[i] < j.PostgresGroups[k] })
	groups := append([]uint32(nil), j.PostgresGroups...)
	seen := map[string]bool{}
	var sharedDeadline time.Time
	parent, cancel := context.WithTimeout(context.Background(), time.Hour)
	defer cancel()
	config, hba, auto, e := b.observeConfiguration(parent, j, func(ctx context.Context, cmd *exec.Cmd) error {
		key := cmd.Args[len(cmd.Args)-1]
		want, allowed := values[key]
		if !allowed || seen[key] {
			t.Fatalf("query escaped finite setting list: %q", cmd.Args)
		}
		seen[key] = true
		path := b.path("/usr/lib/postgresql/18/bin/postgres")
		args := []string{path, "-D", b.data(j), "-c", "config_file=" + values["config_file"], "-C", key}
		if cmd.Path != path || !reflect.DeepEqual(cmd.Args, args) || cmd.Dir != b.data(j) || cmd.Stdin != nil {
			t.Fatalf("configuration query changed its fixed read-only arguments: %q", cmd.Args)
		}
		env := []string{"PATH=/usr/sbin:/usr/bin:/sbin:/bin", "LANG=C.UTF-8", "LC_ALL=C.UTF-8", "HOME=/var/lib/postgresql"}
		if !reflect.DeepEqual(cmd.Env, env) || cmd.Cancel == nil || cmd.WaitDelay != time.Second {
			t.Fatal("configuration reader inherited environment or lost finite child cleanup")
		}
		credential := cmd.SysProcAttr.Credential
		if credential == nil || credential.Uid == 0 || credential.Gid == 0 || credential.Uid != j.PostgresUID || credential.Gid != j.PostgresGID || credential.NoSetGroups || !reflect.DeepEqual(credential.Groups, groups) {
			t.Fatal("configuration reader lost the recorded non-root UID/GID/approved groups")
		}
		credential.Groups[0]++ // Child construction must not mutate the journal.
		if !reflect.DeepEqual(j.PostgresGroups, groups) {
			t.Fatal("child credentials alias retained group identity")
		}
		deadline, ok := ctx.Deadline()
		if !ok || time.Until(deadline) <= 0 || time.Until(deadline) > postgresConfigurationTimeout {
			t.Fatal("configuration queries have no shared finite deadline")
		}
		if !sharedDeadline.IsZero() && !sharedDeadline.Equal(deadline) {
			t.Fatal("each configuration query acquired a new timeout budget")
		}
		sharedDeadline = deadline
		_, e := io.WriteString(cmd.Stdout, want+"\n")
		return e
	})
	if e != nil || len(seen) != len(values) {
		t.Fatalf("all parser values including omitted ssl default were not accepted: %v", e)
	}
	if !bytes.Contains(config, []byte("ssl is omitted")) || !postgresHBA(hba) || !hashSyntax.MatchString(auto) {
		t.Fatal("configuration/HBA/empty override bytes were not returned for normal binding")
	}
}

func TestPostgresConfigurationRejectsEachIncorrectSettingWithoutEchoingValues(t *testing.T) {
	for _, key := range []string{"data_directory", "port", "listen_addresses", "password_encryption", "ssl", "config_file", "hba_file", "ident_file"} {
		t.Run(key, func(t *testing.T) {
			b, j, values := postgresConfigurationFixture(t)
			credentials := postgresCredentials(j)
			_, _, _, e := b.observeConfiguration(context.Background(), j, func(_ context.Context, cmd *exec.Cmd) error {
				name := cmd.Args[len(cmd.Args)-1]
				value := values[name]
				if name == key {
					value = credentials.ControlDSN
				}
				_, e := io.WriteString(cmd.Stdout, value+"\n")
				return e
			})
			if !errors.Is(e, ErrState) || !strings.Contains(e.Error(), "setting "+key+" ") || !strings.Contains(e.Error(), values["config_file"]) {
				t.Fatalf("failed setting/path predicate was lost: %v", e)
			}
			if strings.Contains(e.Error(), "postgres://") || strings.Contains(e.Error(), j.ControlPassword) {
				t.Fatal("unexpected configuration value entered diagnostics")
			}
		})
	}
}

func TestPostgresConfigurationRejectsInvalidCredentialBindingsBeforeExecution(t *testing.T) {
	for name, change := range map[string]func(*postgresJournal){
		"root-uid":              func(j *postgresJournal) { j.PostgresUID = 0 },
		"root-gid":              func(j *postgresJournal) { j.PostgresGID = 0 },
		"missing-groups":        func(j *postgresJournal) { j.PostgresGroups = nil },
		"root-group":            func(j *postgresJournal) { j.PostgresGroups = []uint32{0, j.PostgresGID} },
		"duplicate-group":       func(j *postgresJournal) { j.PostgresGroups = []uint32{j.PostgresGID, j.PostgresGID} },
		"unordered-groups":      func(j *postgresJournal) { j.PostgresGroups = []uint32{j.PostgresGID + 1, j.PostgresGID} },
		"missing-primary-group": func(j *postgresJournal) { j.PostgresGroups = []uint32{j.PostgresGID + 1} },
		"too-many-groups":       func(j *postgresJournal) { j.PostgresGroups = []uint32{1, 2, 3} },
	} {
		t.Run(name, func(t *testing.T) {
			b, j, _ := postgresConfigurationFixture(t)
			change(j)
			_, _, _, e := b.observeConfiguration(context.Background(), j, func(context.Context, *exec.Cmd) error {
				t.Fatal("invalid credential binding reached execution")
				return nil
			})
			if !errors.Is(e, ErrAuthority) || !strings.Contains(e.Error(), "configuration reader") {
				t.Fatalf("invalid privilege binding accepted: %v", e)
			}
		})
	}
}

func TestPostgresConfigurationRetainsNativeCauseAndPrivateDiagnosticContext(t *testing.T) {
	b, j, _ := postgresConfigurationFixture(t)
	preparePostgresState(t, b.m)
	cause := errors.New("fixture native parser exit")
	credentials := postgresCredentials(j)
	_, _, _, e := b.observeConfiguration(context.Background(), j, func(_ context.Context, cmd *exec.Cmd) error {
		_, _ = fmt.Fprintf(cmd.Stderr, "FATAL: configuration syntax at line 19: %s %s %s %s", credentials.ControlDSN, j.SitePassword, j.ControlVerifier, j.Token)
		return cause
	})
	if !errors.Is(e, ErrState) || !errors.Is(e, cause) || !strings.Contains(e.Error(), "line 19") {
		t.Fatalf("native configuration failure cause was lost: %v", e)
	}
	result, failed := b.m.postgresFail(j, "stage-outcome-unknown", "Inspect protected diagnostics.", e)
	if !errors.Is(failed, ErrState) {
		t.Fatal(failed)
	}
	diagnosticPath := filepath.Join(b.m.postgresStateDir(), j.Draft.OperationID+".diagnostic")
	data, re := readPrivate(diagnosticPath, b.m.ownerUID, 64<<10)
	if re != nil {
		t.Fatal(re)
	}
	for _, secret := range []string{credentials.ControlDSN, j.ControlPassword, j.SitePassword, j.ControlVerifier, j.Token} {
		if bytes.Contains(data, []byte(secret)) {
			t.Fatal("credential material entered retained configuration diagnostics")
		}
	}
	for _, context := range []string{"setting data_directory", filepath.Join(b.configDir(j), "postgresql.conf"), "line 19", cause.Error()} {
		if !bytes.Contains(data, []byte(context)) {
			t.Fatalf("useful configuration diagnostic was erased: missing %q", context)
		}
	}
	public, _ := json.Marshal(result)
	if bytes.Contains(public, []byte("line 19")) || bytes.Contains(public, []byte(b.configDir(j))) {
		t.Fatal("private configuration cause entered public result")
	}
}

func TestPostgresConfigurationCancellationPreservesCauseAndDoesNotContinue(t *testing.T) {
	for _, name := range []string{"already-canceled", "already-expired", "during-query"} {
		t.Run(name, func(t *testing.T) {
			b, j, _ := postgresConfigurationFixture(t)
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			expected := context.Canceled
			if name == "already-canceled" {
				cancel()
			}
			if name == "already-expired" {
				var expire context.CancelFunc
				ctx, expire = context.WithDeadline(ctx, time.Now().Add(-time.Second))
				defer expire()
				expected = context.DeadlineExceeded
			}
			calls := 0
			native := errors.New("fixture child terminated")
			_, _, _, e := b.observeConfiguration(ctx, j, func(child context.Context, cmd *exec.Cmd) error {
				calls++
				cancel()
				if child.Err() == nil {
					t.Fatal("child did not inherit caller cancellation")
				}
				return native
			})
			if !errors.Is(e, ErrState) || !errors.Is(e, expected) || !strings.Contains(e.Error(), "setting data_directory") {
				t.Fatalf("cancellation lost its classification/cause/predicate: %v", e)
			}
			if name == "during-query" {
				if calls != 1 || !errors.Is(e, native) {
					t.Fatal("canceled query continued or lost native exit cause")
				}
			} else if calls != 0 {
				t.Fatal("canceled observation launched a query")
			}
		})
	}
}

func TestPostgresConfigurationOutputBoundsAndMalformedValues(t *testing.T) {
	for _, stream := range []string{"stdout", "stderr"} {
		t.Run(stream+"-bound", func(t *testing.T) {
			b, j, _ := postgresConfigurationFixture(t)
			calls := 0
			_, _, _, e := b.observeConfiguration(context.Background(), j, func(_ context.Context, cmd *exec.Cmd) error {
				calls++
				writer := cmd.Stdout
				if stream == "stderr" {
					writer = cmd.Stderr
				}
				_, writeError := io.WriteString(writer, strings.Repeat("x", (64<<10)+1))
				if writeError == nil {
					t.Fatal("oversized child output was not refused")
				}
				return nil // Even an acknowledged zero exit must fail the bound.
			})
			if !errors.Is(e, ErrState) || !strings.Contains(e.Error(), "65536-byte stdout/stderr limit") || calls != 1 {
				t.Fatalf("child output bound was not enforced: %v", e)
			}
		})
	}
	for _, value := range []string{"", "\n", "off\r\n", "off\non\n", "off\x00\n", strings.Repeat("x", 4097)} {
		b, j, _ := postgresConfigurationFixture(t)
		_, _, _, e := b.observeConfiguration(context.Background(), j, func(_ context.Context, cmd *exec.Cmd) error {
			_, _ = io.WriteString(cmd.Stdout, value)
			return nil
		})
		if !errors.Is(e, ErrState) || !strings.Contains(e.Error(), "one bounded value") {
			t.Fatalf("malformed configuration query output accepted: %v", e)
		}
	}
}

func TestPostgresConfigurationPreservesProtectedFilesAndHashBindings(t *testing.T) {
	for _, name := range []string{"config-hash", "hba-hash", "auto-hash", "include", "include-symlink", "hba-policy", "auto-setting", "auto-mode", "config-symlink"} {
		t.Run(name, func(t *testing.T) {
			b, j, values := postgresConfigurationFixture(t)
			path, class := values["config_file"], ErrState
			switch name {
			case "config-hash":
				j.ConfigSHA256 = strings.Repeat("f", 64)
			case "hba-hash":
				path, j.HBASHA256 = values["hba_file"], strings.Repeat("f", 64)
			case "auto-hash":
				path, j.AutoConfigSHA256 = filepath.Join(b.data(j), "postgresql.auto.conf"), strings.Repeat("f", 64)
			case "include":
				path, class = filepath.Join(b.configDir(j), "conf.d"), ErrAuthority
				if e := os.WriteFile(filepath.Join(path, "foreign.conf"), []byte("# foreign\n"), 0600); e != nil {
					t.Fatal(e)
				}
			case "include-symlink":
				path, class = filepath.Join(b.configDir(j), "conf.d"), ErrAuthority
				if e := os.Remove(path); e != nil {
					t.Fatal(e)
				}
				if e := os.Symlink(t.TempDir(), path); e != nil {
					t.Fatal(e)
				}
			case "hba-policy":
				path, class = values["hba_file"], ErrAuthority
				if e := os.WriteFile(path, []byte("host all all 0.0.0.0/0 trust\n"), 0600); e != nil {
					t.Fatal(e)
				}
			case "auto-setting":
				path, class = filepath.Join(b.data(j), "postgresql.auto.conf"), ErrAuthority
				if e := os.WriteFile(path, []byte("ssl='off'\n"), 0600); e != nil {
					t.Fatal(e)
				}
			case "auto-mode":
				path, class = filepath.Join(b.data(j), "postgresql.auto.conf"), ErrAuthority
				if e := os.Chmod(path, 0644); e != nil {
					t.Fatal(e)
				}
			case "config-symlink":
				class = ErrInput
				if e := os.Remove(path); e != nil {
					t.Fatal(e)
				}
				if e := os.Symlink(values["hba_file"], path); e != nil {
					t.Fatal(e)
				}
			}
			_, _, _, e := b.observeConfiguration(context.Background(), j, func(context.Context, *exec.Cmd) error {
				t.Fatal("unsafe/drifted configuration reached execution")
				return nil
			})
			if !errors.Is(e, class) || !strings.Contains(e.Error(), path) {
				t.Fatalf("protected file/hash predicate or classification was lost: %v", e)
			}
		})
	}
}

func TestPostgresConfigurationRejectsChangesBetweenParserQueries(t *testing.T) {
	for _, name := range []string{"config_file", "hba_file", "auto", "include"} {
		t.Run(name, func(t *testing.T) {
			b, j, values := postgresConfigurationFixture(t)
			path, class := values[name], ErrState
			if name == "auto" {
				path = filepath.Join(b.data(j), "postgresql.auto.conf")
			}
			if name == "include" {
				path, class = filepath.Join(b.configDir(j), "conf.d"), ErrAuthority
			}
			calls := 0
			_, _, _, e := b.observeConfiguration(context.Background(), j, func(_ context.Context, cmd *exec.Cmd) error {
				calls++
				key := cmd.Args[len(cmd.Args)-1]
				if key == "ident_file" {
					target := path
					if name == "include" {
						target = filepath.Join(path, "foreign.conf")
					}
					file, e := os.OpenFile(target, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0600)
					if e != nil {
						t.Fatal(e)
					}
					if _, e = file.WriteString("# changed during observation\n"); e != nil {
						t.Fatal(e)
					}
					if e = file.Close(); e != nil {
						t.Fatal(e)
					}
				}
				_, e := io.WriteString(cmd.Stdout, values[key]+"\n")
				return e
			})
			if !errors.Is(e, class) || !strings.Contains(e.Error(), path) || calls != len(values) {
				t.Fatalf("mixed configuration snapshot accepted or unhelpful predicate: %v", e)
			}
			if j.ConfigSHA256 != "" || j.HBASHA256 != "" || j.AutoConfigSHA256 != "" || j.ClusterID != "" {
				t.Fatal("failed observation adopted new physical/configuration bindings")
			}
		})
	}
}

